// RepositoryRules.test.js - Check repository scan parsing, depth, errors, and notifications.
const assert = require("node:assert/strict");
const source = require("../../../Helpers/LoadSource.cjs");
const defaults = source("Helpers/Config.js");
const configuration = source("Helpers/ConfigurationRules.js");
const repositories = source("Helpers/RepositoryRules.js").fromFind("/tmp/one/.git\0/tmp/one/.git\0/tmp/two/.git\0", 5);
assert.equal(repositories.length, 2);
assert.equal(repositories[0].path, "/tmp/one");
const commands = source("Helpers/ScanCommand.js");
const vsCodeCommands = source("Providers/VSCode/VSCodeReadCommands.js");
assert.deepEqual(Array.from(vsCodeCommands.modifiedTime("/tmp/history")), ["timeout", "4s", "stat", "-c", "%Y", "/tmp/history"]);
assert.ok(commands.repositories("/tmp/projects").includes("-print0"));
assert.equal(commands.repositories("/tmp/projects")[1], defaults.repositoryScanTimeout);
assert.equal(commands.repositories("/tmp/projects")[5], String(defaults.defaultRepositoryDepth));
assert.equal(commands.repositories("/tmp/projects", 12)[5], "12");
assert.equal(configuration.repositoryDepth(0), 3);
assert.equal(configuration.repositoryDepth(21), 3);
assert.equal(configuration.repositoryDepth(20), 20);
assert.equal(configuration.scan([], [], 12).depth, 12);
const scanErrors = source("Helpers/ScanErrorRules.js");
assert.match(scanErrors.repository(124, ""), /timed out/);
assert.match(scanErrors.repository(1, "find: Permission denied"), /permission denied/);
assert.match(scanErrors.repository(1, "No such file or directory"), /no longer exists/);
assert.match(scanErrors.forFolder("/home/test/projects", 1, "Permission denied"), /Repository folder \/home\/test\/projects:.*permission denied/);
assert.match(scanErrors.notScanned("/home/test/later", 500), /Repository folder \/home\/test\/later was not scanned.*limit of 500/);
const repositoryNotifications = source("Helpers/RepositoryNotificationRules.js");
assert.deepEqual(Array.from(repositoryNotifications.newlyAdded(["/old"], ["/old"])), []);
assert.deepEqual(Array.from(repositoryNotifications.newlyAdded(["/old"], ["/old", "/new"])), ["/new"]);
assert.deepEqual(Array.from(repositoryNotifications.pending(["/new"], ["/new", "/later"], ["/later"])), ["/later"]);
assert.deepEqual(Array.from(repositoryNotifications.messages([{ path: "/old", message: "old error" }, { path: "/new", message: "new error" }], ["/new"])), ["new error"]);
// A folder's own latest error is returned for its settings row; a folder with no error gets an empty string.
assert.equal(scanErrors.forConfiguredFolder("/home/test/projects/", [{ path: "/home/test/projects", message: "denied" }]), "denied");
assert.equal(scanErrors.forConfiguredFolder("/home/test/other", [{ path: "/home/test/projects", message: "denied" }]), "");
assert.equal(scanErrors.forConfiguredFolder("relative/path", [{ path: "relative/path", message: "x" }]), "");
assert.equal(scanErrors.forConfiguredFolder("/home/test/projects", undefined), "");
// The JSON history read is capped: head fetches one byte past the limit so an oversize file can be refused.
const jsonCommand = vsCodeCommands.json("/tmp/storage.json");
assert.deepEqual(Array.from(jsonCommand.slice(0, 4)), ["timeout", "4s", "head", "-c"]);
assert.equal(jsonCommand[4], String(source("Providers/VSCode/VSCodeConstants.js").MAX_HISTORY_BYTES + 1));
assert.equal(jsonCommand[5], "/tmp/storage.json");
